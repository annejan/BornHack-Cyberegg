/// Is pixel (`x`, `y`) set in `plane`?
fn lit(plane: &[u8; 768], x: usize, y: usize) -> bool {
    plane[y * ROW_BYTES + x / 8] & (0x80 >> (x % 8)) != 0
}

/// Draw the picture's black and red pixels with its top-left at `top_left`.
/// White is left untouched.
pub fn draw_realm_picture<D: DrawTarget<Color = TriColor>>(
    display: &mut D,
    top_left: Point,
) -> Result<(), D::Error> {
    let px = (0..HEIGHT as usize).flat_map(move |y| {
        (0..WIDTH as usize).filter_map(move |x| {
            let color = if lit(&BLACK_PLANE, x, y) {
                BLACK
            } else if lit(&RED_PLANE, x, y) {
                RED
            } else {
                return None;
            };
            Some(Pixel(top_left + Point::new(x as i32, y as i32), color))
        })
    });
    display.draw_iter(px)
}

#[cfg(all(test, feature = "simulator"))]
mod tests {
    use super::*;

    #[test]
    fn planes_match_the_png() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/assets/bornpets-unicorn-realm.png");
        let img = image::open(path).unwrap().to_rgb8();
        assert_eq!((img.width(), img.height()), (WIDTH, HEIGHT));
        for (x, y, p) in img.enumerate_pixels() {
            let (x, y) = (x as usize, y as usize);
            let want = match p.0 {
                [0, 0, 0] => (true, false),
                [220, 0, 0] => (false, true),
                [255, 255, 255] => (false, false),
                other => panic!("unexpected colour {other:?} at {x},{y}"),
            };
            assert_eq!((lit(&BLACK_PLANE, x, y), lit(&RED_PLANE, x, y)), want, "{x},{y}");
        }
    }
}
